        /// <summary>
        /// Find the identities that contain a value (an access key id, a secret, a password or token seen in an alert or a leak),
        /// so that the probe trap log tells what client got it and when ("Probe decoy ... identity N ... served to ...").
        /// </summary>
        /// <param name="value">The value (or a part of it, at least 8 chars)</param>
        /// <returns>The identities (several for a real AWS canary key, that is shared round robin)</returns>
        public IReadOnlyList<int> FindIdentity(String value)
        {
            var res = new List<int>();
            value = value?.Trim();
            if (String.IsNullOrEmpty(value) || (value.Length < 8))
                return res;
            for (int k = 0; k < IdentityCount; ++k)
            {
                var d = GetIdentityData(k);
                foreach (var x in d.All)
                {
                    if (x.Contains(value, StringComparison.Ordinal))
                    {
                        res.Add(k);
                        break;
                    }
                }
            }
            return res;
        }

