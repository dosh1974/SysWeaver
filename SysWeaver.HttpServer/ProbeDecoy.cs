        /// <summary>
        /// Derive a stable, secret value: chars of an alphabet from HMAC-SHA256(secret, identity | field | block)
        /// </summary>
        String Chars(int k, String field, String alphabet, int n)
        {
            var sb = new StringBuilder(n);
            Span<Byte> h = stackalloc Byte[32];
            var al = alphabet.Length;
            for (int block = 0; sb.Length < n; ++block)
            {
                HMACSHA256.HashData(Secret, Encoding.UTF8.GetBytes(String.Concat(k.ToString(CultureInfo.InvariantCulture), "|", field, "|", block.ToString(CultureInfo.InvariantCulture))), h);
                foreach (var b in h)
                {
                    //  Rejection sampling keeps every char equally likely
                    var lim = 256 - (256 % al);
                    if (b >= lim)
                        continue;
                    sb.Append(alphabet[b % al]);
                    if (sb.Length >= n)
                        break;
                }
            }
            return sb.ToString();
        }

