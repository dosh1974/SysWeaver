        const int RsaKeyCount = 16;

        readonly RSA[] RsaKeys = new RSA[RsaKeyCount];
        readonly Lock RsaLock = new();

        /// <summary>
        /// The RSA keys (for ssh keys and service accounts), created on first use (not derived: an RSA key can't be created from a seed),
        /// so they change on a restart; use the log to trace one
        /// </summary>
        RSA GetRsa(int i)
        {
            var r = Volatile.Read(ref RsaKeys[i]);
            if (r != null)
                return r;
            lock (RsaLock)
            {
                r = RsaKeys[i];
                if (r == null)
                {
                    r = RSA.Create(2048);
                    Volatile.Write(ref RsaKeys[i], r);
                }
            }
            return r;
        }

        static void SshString(List<Byte> to, ReadOnlySpan<Byte> data)
        {
            var l = data.Length;
            to.Add((Byte)(l >> 24));
            to.Add((Byte)(l >> 16));
            to.Add((Byte)(l >> 8));
            to.Add((Byte)l);
            foreach (var b in data)
                to.Add(b);
        }

        static void SshMpInt(List<Byte> to, Byte[] value)
        {
            int i = 0;
            while ((i < value.Length - 1) && (value[i] == 0))
                ++i;
            var v = value.AsSpan(i);
            if ((v[0] & 0x80) != 0)
            {
                var t = new Byte[v.Length + 1];
                v.CopyTo(t.AsSpan(1));
                SshString(to, t);
                return;
            }
            SshString(to, v);
        }

        /// <summary>
        /// The OpenSSH public key line ("ssh-rsa AAAA...") of an RSA key
        /// </summary>
        static String SshPublicKey(RSA rsa)
        {
            var p = rsa.ExportParameters(false);
            var b = new List<Byte>(300);
            SshString(b, "ssh-rsa"u8);
            SshMpInt(b, p.Exponent);
            SshMpInt(b, p.Modulus);
            return "ssh-rsa " + Convert.ToBase64String(b.ToArray());
        }

