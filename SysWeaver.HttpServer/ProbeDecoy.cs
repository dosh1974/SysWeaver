    /// <summary>
    /// The kind of secret a probe url asks for (see <see cref="ProbeDecoy.Detect(string)"/>)
    /// </summary>
    public enum ProbePayloadTypes : byte
    {
        /// <summary>Not a known secret file: the probe trap answers with its hostile answer</summary>
        None = 0,
        /// <summary>.env*, env, env.bak</summary>
        EnvFile,
        /// <summary>.aws/*, .s3cfg, aws-credentials.txt</summary>
        AwsCredentials,
        /// <summary>.git/*, .git-credentials, .hg/*, .svn/*</summary>
        VcsInternals,
        /// <summary>*.tfstate*, *.tfvars, .terraform/*, .terraformrc</summary>
        TerraformState,
        /// <summary>.kube/*</summary>
        KubeConfig,
        /// <summary>.docker/config.json, docker-compose*.yml, compose.yml</summary>
        DockerConfig,
        /// <summary>credentials.*, .npmrc, .pypirc, .netrc, .pgpass, .htpasswd, .my.cnf, secrets.*</summary>
        GenericCredentials,
        /// <summary>Backups of web app configurations: wp-config.php.bak, config.php.bak, appsettings*.json, web.config, config/database.yml, config/master.key ...</summary>
        WebAppConfig,
        /// <summary>backup.sql, dump.sql, database.sql ...</summary>
        DatabaseDump,
        /// <summary>Cloud service account keys: service-account.json, .config/gcloud/application_default_credentials.json ...</summary>
        CloudCredentials,
        /// <summary>sftp-config.json, .vscode/sftp.json, .ftpconfig, FileZilla sitemanager.xml</summary>
        FtpConfig,
        /// <summary>.ssh/*, id_rsa, id_rsa.pub, authorized_keys</summary>
        SshKey,
        /// <summary>.bash_history, .zsh_history, .mysql_history, .psql_history</summary>
        ShellHistory,
    }

    /// <summary>
    /// Believable decoy secret files for the probe trap (see <see cref="HttpProbeTrapParams.UseDecoys"/>): a probe for a known secret file
    /// (".env", ".aws/credentials", ".git/config" etc) gets a plain, normal looking file with credentials that belong to nothing, instead of the
    /// hostile answer (a strange answer tells a probe that it found a honeypot, a working looking secret makes it spend time on using it).
    /// </summary>
    /// <remarks>
    /// <para>
    /// Every value is derived (HMAC-SHA256) from a secret of this installation, stored in the application key value store: the values are stable across
    /// restarts (an alert can be traced back with <see cref="FindIdentity(string)"/>), but nobody can compute them, so they can't be used to recognize
    /// a SysWeaver decoy (fixed or publicly seeded values could all be generated by anyone that has the source).
    /// </para>
    /// <para>
    /// A client address always gets the same identity (one of <see cref="HttpProbeTrapParams.DecoyIdentities"/>): every file served to one probe
    /// tells the same story (the database password of the .env is the one of docker-compose.yml), and the identity tells what probe got the values.
    /// </para>
    /// <para>
    /// Real tripwires: create AWS IAM users without any permissions, create access keys for them, and list them in <see cref="HttpProbeTrapParams.CanaryAwsKeys"/>.
    /// They replace the generated AWS keys (round robin over the identities): every use of a key then shows up in CloudTrail (AccessDenied, with the
    /// address and user agent of the thief), use the log of the probe trap ("Probe decoy ... served") to find what probe got it and when.
    /// </para>
    /// <para>No marker of any kind is put in the files: the uniqueness is in the values, the mapping stays on the server.</para>
    /// Thread safe, payloads are built on first use and cached.
    /// </remarks>
    public sealed class ProbeDecoy
    {
        /// <summary>
        /// Create a decoy generator
        /// </summary>
        /// <param name="secret">The secret of this installation (at least 16 bytes), all values are derived from it</param>
        /// <param name="name">The name used in the files (an app / service name, ex: "checkout-api"), null or empty for "app"</param>
        /// <param name="identities">The number of identities (sets of credentials), at least 1</param>
        /// <param name="awsKeys">Optional real AWS canary keys ("AKIA...:secret"), used instead of generated ones</param>
        /// <exception cref="ArgumentException">The secret is too short, or an AWS key isn't "key id:secret"</exception>
        public ProbeDecoy(Byte[] secret, String name = null, int identities = 512, IEnumerable<String> awsKeys = null)
        {
            ArgumentNullException.ThrowIfNull(secret);
            if (secret.Length < 16)
                throw new ArgumentException("The secret must be at least 16 bytes", nameof(secret));
            Secret = secret;
            Name = CleanName(name);
            Domain = Name + ".internal";
            IdentityCount = Math.Max(1, identities);
            var keys = new List<(String, String)>();
            if (awsKeys != null)
            {
                foreach (var x in awsKeys)
                {
                    var t = x?.Trim();
                    if (String.IsNullOrEmpty(t))
                        continue;
                    var i = t.IndexOf(':');
                    if ((i != 20) || (t.Length < 30) || !(t.StartsWith("AKIA", StringComparison.Ordinal) || t.StartsWith("ASIA", StringComparison.Ordinal)))
                        throw new ArgumentException("An AWS canary key must be \"<20 char access key id>:<secret access key>\", found " + t.Substring(0, Math.Min(4, t.Length)).ToQuoted() + "...", nameof(awsKeys));
                    keys.Add((t.Substring(0, 20), t.Substring(21)));
                }
            }
            AwsKeys = keys.ToArray();
            Identities = new IdentityData[IdentityCount];
        }

        readonly Byte[] Secret;
        readonly String Name;
        readonly String Domain;
        readonly (String KeyId, String Secret)[] AwsKeys;

        /// <summary>
        /// The number of identities
        /// </summary>
        public readonly int IdentityCount;

        /// <summary>
        /// True if real AWS canary keys are used
        /// </summary>
        public bool HaveRealAwsKeys => AwsKeys.Length > 0;

        static String CleanName(String name)
        {
            var sb = new StringBuilder();
            foreach (var c in (name ?? "").ToLowerInvariant())
            {
                if (((c >= 'a') && (c <= 'z')) || ((c >= '0') && (c <= '9')))
                    sb.Append(c);
                else if ((sb.Length > 0) && (sb[sb.Length - 1] != '-'))
                    sb.Append('-');
            }
            var s = sb.ToString().Trim('-');
            return s.Length == 0 ? "app" : (s.Length > 32 ? s.Substring(0, 32).Trim('-') : s);
        }

