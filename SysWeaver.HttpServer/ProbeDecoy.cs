        #region Variants

        enum V
        {
            Env, AwsIni, S3Cfg, Ignore,
            GitConfig, GitHead, GitRef, GitPackedRefs, GitLogs, GitIndex, GitDescription, GitCreds, HgRequires, SvnEntries,
            TfState, TfVars, TerraformRc,
            Kube,
            DockerAuth, Compose,
            CredJson, CredXml, CredPlain, Npmrc, Pypirc, Netrc, Pgpass, Htpasswd, MyCnf, SecretsYaml,
            WpConfig, PhpConfig, AppSettings, WebConfig, RailsDb, RailsSecrets, RailsMasterKey,
            SqlDump,
            GcpServiceAccount,
            SftpJson, FileZilla, FtpConfig,
            SshRsa, SshPub, AuthorizedKeys, KnownHosts, SshConfig,
            BashHistory, MysqlHistory,
            Count
        }

        static String MimeOf(V v) => v switch
        {
            V.GitIndex => "application/octet-stream",
            V.TfState or V.DockerAuth or V.CredJson or V.AppSettings or V.GcpServiceAccount or V.SftpJson => "application/json",
            V.CredXml or V.WebConfig or V.FileZilla => "application/xml",
            V.Kube or V.Compose or V.RailsDb or V.RailsSecrets or V.SecretsYaml => "text/yaml",
            _ => "text/plain",
        };

        static V Variant(ProbePayloadTypes t, String url)
        {
            var u = url.AsSpan();
            var q = u.IndexOfAny('?', '#');
            if (q >= 0)
                u = u.Slice(0, q);
            switch (t)
            {
                case ProbePayloadTypes.EnvFile:
                    return V.Env;
                case ProbePayloadTypes.AwsCredentials:
                    return Contains(u, ".s3cfg") ? V.S3Cfg : V.AwsIni;
                case ProbePayloadTypes.VcsInternals:
                    if (Contains(u, ".gitignore") || Contains(u, ".gitattributes") || Contains(u, ".gitmodules") || Contains(u, ".hgignore") || Contains(u, ".svnignore"))
                        return V.Ignore;
                    if (Contains(u, ".git-credentials"))
                        return V.GitCreds;
                    if (Contains(u, ".hg/"))
                        return V.HgRequires;
                    if (Contains(u, ".svn/"))
                        return V.SvnEntries;
                    if (Ends(u, "/index"))
                        return V.GitIndex;
                    if (Ends(u, "/packed-refs"))
                        return V.GitPackedRefs;
                    if (Contains(u, "/logs/"))
                        return V.GitLogs;
                    if (Ends(u, "/description"))
                        return V.GitDescription;
                    if (Ends(u, "/ORIG_HEAD") || Ends(u, "/FETCH_HEAD") || Contains(u, "/refs/"))
                        return V.GitRef;
                    if (Ends(u, "/HEAD"))
                        return V.GitHead;
                    return V.GitConfig;
                case ProbePayloadTypes.TerraformState:
                    if (Contains(u, ".terraformrc") || Ends(u, "credentials.tfrc.json"))
                        return V.TerraformRc;
                    return Ends(u, ".tfvars") ? V.TfVars : V.TfState;
                case ProbePayloadTypes.KubeConfig:
                    return V.Kube;
                case ProbePayloadTypes.DockerConfig:
                    if (Contains(u, ".dockerignore"))
                        return V.Ignore;
                    return Contains(u, "config.json") ? V.DockerAuth : V.Compose;
                case ProbePayloadTypes.WebAppConfig:
                    if (Contains(u, "wp-config"))
                        return V.WpConfig;
                    if (Contains(u, ".php"))
                        return V.PhpConfig;
                    if (Contains(u, "appsettings"))
                        return V.AppSettings;
                    if (Contains(u, "web.config"))
                        return V.WebConfig;
                    if (Ends(u, "master.key"))
                        return V.RailsMasterKey;
                    if (Ends(u, "secrets.yml"))
                        return V.RailsSecrets;
                    return V.RailsDb;
                case ProbePayloadTypes.DatabaseDump:
                    return V.SqlDump;
                case ProbePayloadTypes.CloudCredentials:
                    return V.GcpServiceAccount;
                case ProbePayloadTypes.FtpConfig:
                    if (Contains(u, "sitemanager") || Contains(u, "filezilla"))
                        return V.FileZilla;
                    if (Contains(u, ".ftpconfig"))
                        return V.FtpConfig;
                    return V.SftpJson;
                case ProbePayloadTypes.SshKey:
                    if (Ends(u, ".pub"))
                        return V.SshPub;
                    if (Ends(u, "authorized_keys"))
                        return V.AuthorizedKeys;
                    if (Ends(u, "known_hosts"))
                        return V.KnownHosts;
                    if (Ends(u, "/config"))
                        return V.SshConfig;
                    return V.SshRsa;
                case ProbePayloadTypes.ShellHistory:
                    return (Contains(u, "mysql") || Contains(u, "psql")) ? V.MysqlHistory : V.BashHistory;
                default:
                    if (Contains(u, ".npmrc"))
                        return V.Npmrc;
                    if (Contains(u, ".pypirc"))
                        return V.Pypirc;
                    if (Contains(u, ".netrc"))
                        return V.Netrc;
                    if (Contains(u, ".pgpass"))
                        return V.Pgpass;
                    if (Contains(u, ".htpasswd"))
                        return V.Htpasswd;
                    if (Contains(u, ".my.cnf"))
                        return V.MyCnf;
                    if (Contains(u, "secret") && (Ends(u, ".yml") || Ends(u, ".yaml")))
                        return V.SecretsYaml;
                    if (Ends(u, ".json"))
                        return V.CredJson;
                    if (Ends(u, ".xml"))
                        return V.CredXml;
                    return V.CredPlain;
            }
        }

        #endregion//Variants

        #region Payloads

        /// <summary>
        /// Get the decoy file for a probe url, for the identity of a client.
        /// </summary>
        /// <param name="mime">The content type of the file</param>
        /// <param name="identity">The identity that was used (see <see cref="GetIdentity(string)"/>, <see cref="FindIdentity(string)"/>), -1 for none</param>
        /// <param name="url">The url</param>
        /// <param name="type">The kind of secret (from <see cref="Detect(string)"/>)</param>
        /// <param name="clientKey">A key of the client (ex: its address), the same key always gets the same identity; null for a random identity</param>
        /// <returns>The file, empty for <see cref="ProbePayloadTypes.None"/></returns>
        public ReadOnlyMemory<Byte> GetPayload(out String mime, out int identity, String url, ProbePayloadTypes type, String clientKey = null)
        {
            if (type == ProbePayloadTypes.None)
            {
                mime = "text/plain";
                identity = -1;
                return ReadOnlyMemory<Byte>.Empty;
            }
            var v = Variant(type, url ?? "");
            var k = clientKey == null ? Random.Shared.Next(IdentityCount) : GetIdentity(clientKey);
            identity = k;
            mime = MimeOf(v);
            var key = (int)v * IdentityCount + k;
            if (Payloads.TryGetValue(key, out var p))
                return p;
            p = Encoding.UTF8.GetBytes(Build(v, GetIdentityData(k)));
            if (v == V.GitIndex)
                p = GitIndex;
            Payloads.TryAdd(key, p);
            return p;
        }

        readonly ConcurrentDictionary<int, Byte[]> Payloads = new();

        /// <summary>
        /// The identity of a client key (keyed hash of the key, modulo <see cref="IdentityCount"/>)
        /// </summary>
        /// <param name="clientKey">The client key (ex: its address)</param>
        /// <returns>The identity</returns>
        public int GetIdentity(String clientKey)
        {
            Span<Byte> h = stackalloc Byte[32];
            HMACSHA256.HashData(Secret, Encoding.UTF8.GetBytes("client|" + (clientKey ?? "")), h);
            return (int)(BitConverter.ToUInt32(h) % (uint)IdentityCount);
        }

