        static readonly (String Stem, ProbePayloadTypes Type)[] DotStems =
        [
            (".env", ProbePayloadTypes.EnvFile), (".git", ProbePayloadTypes.VcsInternals),
            (".hg", ProbePayloadTypes.VcsInternals), (".svn", ProbePayloadTypes.VcsInternals),
            (".bzr", ProbePayloadTypes.VcsInternals), (".aws", ProbePayloadTypes.AwsCredentials),
            (".s3cfg", ProbePayloadTypes.AwsCredentials), (".kube", ProbePayloadTypes.KubeConfig),
            (".docker", ProbePayloadTypes.DockerConfig), (".terraform", ProbePayloadTypes.TerraformState),
            (".ssh", ProbePayloadTypes.SshKey), (".npmrc", ProbePayloadTypes.GenericCredentials),
            (".pypirc", ProbePayloadTypes.GenericCredentials), (".netrc", ProbePayloadTypes.GenericCredentials),
            (".pgpass", ProbePayloadTypes.GenericCredentials), (".htpasswd", ProbePayloadTypes.GenericCredentials),
            (".my.cnf", ProbePayloadTypes.GenericCredentials), (".ftpconfig", ProbePayloadTypes.FtpConfig),
            (".bash_history", ProbePayloadTypes.ShellHistory), (".zsh_history", ProbePayloadTypes.ShellHistory),
            (".mysql_history", ProbePayloadTypes.ShellHistory), (".psql_history", ProbePayloadTypes.ShellHistory),
        ];

        static readonly String[] EnvExt =
        [
            "txt", "bak", "old", "orig", "save", "backup", "local", "dev", "prod", "production", "staging",
            "test", "live", "sample", "example", "dist", "template", "conf", "cfg", "ini", "json", "yml", "yaml", "~"
        ];

        static readonly String[] CrdExt = ["json", "xml", "txt", "yml", "yaml", "bak", "old", "orig", "save", "backup", "csv", "ini", "conf", "pem", "key"];

        /// <summary>
        /// The extensions of backup copies of a source file (ex: "wp-config.php.bak"): the server serves them as text, unlike the file itself
        /// </summary>
        static readonly String[] BackupExt = ["bak", "old", "orig", "save", "backup", "txt", "swp", "~", "1", "2", "dist", "copy", "tmp", "inc"];

        static readonly String[] PhpConfigs = ["wp-config.php", "config.php", "configuration.php", "settings.php", "localsettings.php", "config.inc.php", "database.php", "db.php"];

        static readonly String[] DumpStems = ["backup", "dump", "database", "db", "data", "mysql", "site", "wordpress", "wp", "prod", "production", "www", "sql", "users", "db_backup", "database_backup"];

        /// <summary>
        /// Multi substring prefilter: a cheap reject for the (legitimate) urls that can't be a probe
        /// </summary>
        static readonly SearchValues<String> Prefilter = SearchValues.Create(
        [
            ".env", ".git", ".hg", ".svn", ".bzr", ".aws", ".s3cfg", ".kube", ".docker", ".terraform",
            ".ssh", ".npmrc", ".pypirc", ".netrc", ".pgpass", ".htpasswd", ".bash_history", ".mysql_history",
            ".my.cnf", ".ftpconfig", ".zsh_history", ".psql_history", ".vscode", ".config",
            "env", "credentials", "terraform", "compose", ".tfstate", ".tfvars",
            "config", "settings", ".php", "appsettings", "web.config", ".sql", "sftp", "filezilla", "sitemanager",
            "id_rsa", "id_ecdsa", "authorized_keys", "service-account", "gcp-key", "application_default_credentials",
            "master.key", "secrets"
        ], StringComparison.OrdinalIgnoreCase);

        /// <summary>
        /// Detect what kind of secret file an url probes for (no allocations).
        /// </summary>
        /// <param name="url">The (local) url, with or without a leading '/', the query is ignored</param>
        /// <returns>The kind of secret, <see cref="ProbePayloadTypes.None"/> if it isn't a known secret file</returns>
        public static ProbePayloadTypes Detect(String url)
        {
            if (String.IsNullOrEmpty(url))
                return ProbePayloadTypes.None;
            ReadOnlySpan<Char> s = url.AsSpan();
            int cut = s.IndexOfAny('?', '#');
            if (cut >= 0)
                s = s.Slice(0, cut);
            if ((s.Length > 0) && (s[0] == '/'))
                s = s.Slice(1);
            if (s.Length == 0)
                return ProbePayloadTypes.None;
            if (!s.ContainsAny(Prefilter))
                return ProbePayloadTypes.None;

            //  Files inside dot folders that aren't secrets by the folder name alone
            if (Ends(s, ".vscode/sftp.json"))
                return ProbePayloadTypes.FtpConfig;
            if (Ends(s, ".config/gcloud/application_default_credentials.json") || Ends(s, ".config/gcloud/credentials.json"))
                return ProbePayloadTypes.CloudCredentials;

            //  1) dot prefixed segment at any depth, known stems only
            int start = 0;
            while (start <= s.Length)
            {
                int rel = s.Slice(start).IndexOf('/');
                int end = rel < 0 ? s.Length : start + rel;
                var seg = s.Slice(start, end - start);
                if ((seg.Length > 1) && (seg[0] == '.') && !Eq(seg, "..") && !Eq(seg, ".well-known") && !seg.StartsWith(".github", StringComparison.OrdinalIgnoreCase))
                {
                    foreach (var x in DotStems)
                        if (seg.StartsWith(x.Stem, StringComparison.OrdinalIgnoreCase))
                            return x.Type;
                }
                if (rel < 0)
                    break;
                start = end + 1;
            }

            //  2) known two segment paths (Rails)
            if (Eq(s, "config/database.yml") || Eq(s, "config/secrets.yml") || Eq(s, "config/master.key") || Eq(s, "config/storage.yml"))
                return ProbePayloadTypes.WebAppConfig;
            if (Eq(s, "filezilla/sitemanager.xml"))
                return ProbePayloadTypes.FtpConfig;

            //  3) bare root level file names (single segment only: "api/credentials" is safe)
            var body = s;
            if (body.IndexOf('/') >= 0)
                return ProbePayloadTypes.None;

            if ((body.StartsWith("docker-compose", StringComparison.OrdinalIgnoreCase) && (Ends(body, ".yml") || Ends(body, ".yaml"))) || Eq(body, "compose.yml") || Eq(body, "compose.yaml"))
                return ProbePayloadTypes.DockerConfig;

            if (Eq(body, "terraform.tfvars") || Eq(body, "terraform.tfstate") ||
                body.StartsWith("terraform.tfstate.", StringComparison.OrdinalIgnoreCase) ||
                Ends(body, ".tfstate") || Ends(body, ".tfvars") || Ends(body, ".tfstate.backup"))
                return ProbePayloadTypes.TerraformState;

            //  Web app configurations: backups of php sources (the source itself is executed by a real server, so it returns nothing),
            //  asp.net settings, web.config
            foreach (var p in PhpConfigs)
            {
                if ((body.Length > p.Length) && body.StartsWith(p, StringComparison.OrdinalIgnoreCase))
                {
                    var rest = body.Slice(p.Length);
                    if (((rest.Length > 1) && (rest[0] == '.') && In(rest.Slice(1), BackupExt)) || Eq(rest, "~"))
                        return ProbePayloadTypes.WebAppConfig;
                }
            }
            if (Eq(body, "appsettings.json") || (body.StartsWith("appsettings.", StringComparison.OrdinalIgnoreCase) && Ends(body, ".json")))
                return ProbePayloadTypes.WebAppConfig;
            if (Eq(body, "web.config") || (body.StartsWith("web.config.", StringComparison.OrdinalIgnoreCase) && In(body.Slice(11), BackupExt)))
                return ProbePayloadTypes.WebAppConfig;

            if (Eq(body, "sftp-config.json") || Eq(body, "filezilla.xml") || Eq(body, "sitemanager.xml"))
                return ProbePayloadTypes.FtpConfig;

            if (Eq(body, "id_rsa") || Eq(body, "id_rsa.pub") || Eq(body, "id_ecdsa") || Eq(body, "authorized_keys"))
                return ProbePayloadTypes.SshKey;

            if (Eq(body, "service-account.json") || Eq(body, "serviceaccount.json") || Eq(body, "service_account.json") ||
                Eq(body, "gcp-key.json") || Eq(body, "gcloud.json") || Eq(body, "application_default_credentials.json"))
                return ProbePayloadTypes.CloudCredentials;

            int dot = body.IndexOf('.');
            var stem = dot < 0 ? body : body.Slice(0, dot);
            var ext = dot < 0 ? default : body.Slice(dot + 1);

            if (Eq(ext, "sql") && In(stem, DumpStems))
                return ProbePayloadTypes.DatabaseDump;
            if (Eq(body, "env") || (Eq(stem, "env") && In(ext, EnvExt)))
                return ProbePayloadTypes.EnvFile;
            if (Eq(stem, "aws-credentials") && In(ext, CrdExt))
                return ProbePayloadTypes.AwsCredentials;
            if (Eq(body, "credentials") || (Eq(stem, "credentials") && In(ext, CrdExt)))
                return ProbePayloadTypes.GenericCredentials;
            if ((Eq(stem, "secrets") || Eq(stem, "secret")) && (Eq(ext, "json") || Eq(ext, "yml") || Eq(ext, "yaml")))
                return ProbePayloadTypes.GenericCredentials;
            return ProbePayloadTypes.None;
        }

        /// <summary>
        /// Where a decoy rule matches (see <see cref="GetRules"/>)
        /// </summary>
        public enum RuleScopes
        {
            /// <summary>The url ends with the pattern</summary>
            UrlEnd,
            /// <summary>A folder or file name at any depth starts with the pattern</summary>
            AnySegment,
            /// <summary>The whole url (from the site root)</summary>
            Root,
        }

        /// <summary>
        /// Describe the rules of <see cref="Detect(string)"/> (built from the same lists, keep in sync with it when adding a rule).
        /// Patterns use {a,b} for alternatives and * for any text.
        /// </summary>
        /// <returns>The rules: pattern, scope and the kind of secret, in the order they are tested</returns>
        public static IEnumerable<(String Pattern, RuleScopes Scope, ProbePayloadTypes Type)> GetRules()
        {
            static String Alt(IEnumerable<String> x) => String.Concat("{", String.Join(',', x), "}");
            yield return (".vscode/sftp.json", RuleScopes.UrlEnd, ProbePayloadTypes.FtpConfig);
            yield return (".config/gcloud/{application_default_credentials,credentials}.json", RuleScopes.UrlEnd, ProbePayloadTypes.CloudCredentials);
            foreach (var x in DotStems)
                yield return (x.Stem + "*", RuleScopes.AnySegment, x.Type);
            yield return ("config/{database.yml,secrets.yml,master.key,storage.yml}", RuleScopes.Root, ProbePayloadTypes.WebAppConfig);
            yield return ("filezilla/sitemanager.xml", RuleScopes.Root, ProbePayloadTypes.FtpConfig);
            yield return ("{docker-compose*.yml,docker-compose*.yaml,compose.yml,compose.yaml}", RuleScopes.Root, ProbePayloadTypes.DockerConfig);
            yield return ("{terraform.tfvars,terraform.tfstate,terraform.tfstate.*,*.tfstate,*.tfvars,*.tfstate.backup}", RuleScopes.Root, ProbePayloadTypes.TerraformState);
            yield return (String.Concat(Alt(PhpConfigs), ".", Alt(BackupExt), " or ", Alt(PhpConfigs), "~"), RuleScopes.Root, ProbePayloadTypes.WebAppConfig);
            yield return ("{appsettings.json,appsettings.*.json}", RuleScopes.Root, ProbePayloadTypes.WebAppConfig);
            yield return (String.Concat("web.config or web.config.", Alt(BackupExt)), RuleScopes.Root, ProbePayloadTypes.WebAppConfig);
            yield return ("{sftp-config.json,filezilla.xml,sitemanager.xml}", RuleScopes.Root, ProbePayloadTypes.FtpConfig);
            yield return ("{id_rsa,id_rsa.pub,id_ecdsa,authorized_keys}", RuleScopes.Root, ProbePayloadTypes.SshKey);
            yield return ("{service-account.json,serviceaccount.json,service_account.json,gcp-key.json,gcloud.json,application_default_credentials.json}", RuleScopes.Root, ProbePayloadTypes.CloudCredentials);
            yield return (String.Concat(Alt(DumpStems), ".sql"), RuleScopes.Root, ProbePayloadTypes.DatabaseDump);
            yield return (String.Concat("env or env.", Alt(EnvExt)), RuleScopes.Root, ProbePayloadTypes.EnvFile);
            yield return (String.Concat("aws-credentials.", Alt(CrdExt)), RuleScopes.Root, ProbePayloadTypes.AwsCredentials);
            yield return (String.Concat("credentials or credentials.", Alt(CrdExt)), RuleScopes.Root, ProbePayloadTypes.GenericCredentials);
            yield return ("{secrets,secret}.{json,yml,yaml}", RuleScopes.Root, ProbePayloadTypes.GenericCredentials);
        }

