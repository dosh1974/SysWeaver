/**
 * @file smShared.js - helpers shared by the ServerManager pages (server.js, keys.js, serviceInfo.js, versionInfo.js).
 * Classic script, loaded with `<script defer>` after ../sw/core.js and ../sw/ui.js (and before the page script).
 * No side effects at load time besides defining the single global `SmShared`.
 *
 * Contents:
 * - chart / metrics urls (chart tiles are iframes of ../chart/chart.html fetching ../ServerManager/<api>),
 * - a flicker free child reconciler for polled lists (`ChildUpdater`),
 * - upload targets on top of common/fileUploader.js (`UploadTarget`; only the public `fileUploaderSetup` is used),
 * - small DOM helpers (`TimeCell`),
 * - Design v2 page parts on the shared ui components: `KpiSub` (KPI level as a badge), `UploadButton` (an upload / drop button), `FillTable` (a live table in a fill page).
 *
 * Conventions: chart API names follow the C# pattern `Get<X>Chart`, `Get<X>HistoryShortChart`, `Get<X>HistoryChart`,
 * optionally followed by `?<arg>` (ex: `GetDriveChart?0`, `GetServiceCpuChart?"name"`). Url parameters are encoded with
 * encodeURIComponent (the pages decode them with URLSearchParams, so the unencoded links generated by C# keep working).
 */
(function () {
    "use strict";

    /** Upload status codes used here (mirror C# FileUploadStatus / common/fileUploader.js UploadStatus). */
    const UploadOk = 0;
    /** @type {number} The file was already uploaded (same hash). */
    const UploadAlready = 1;

    /** @type {number|string} Time zone of the chart time labels (chart.html timeoffset: minutes or "local"), see UseServerTimeZone. */
    let TimeOffset = "local";

    /**
     * The url of a chart page. Time labels (history charts, UTC from the server) are shown in the time zone set by
     * UseServerTimeZone (default: the viewer's local time), so they match the clock of the page.
     * @param {string} api - Chart API name relative to ../ServerManager/ (may carry "?<arg>").
     * @param {string} [extra] - Extra (already encoded) query string, starting with "&".
     * The chart page polls only the api (the same requests as the original chart tiles; the server smooths the cpu value itself).
     * @returns {string} "../chart/chart.html?q=../ServerManager/<api>&timeoffset=<tz><extra>".
     */
    function ChartUrl(api, extra) {
        return "../chart/chart.html?q=" + encodeURIComponent("../ServerManager/" + api) + "&timeoffset=" + encodeURIComponent(String(TimeOffset)) + (extra || "");
    }

    /**
     * The url of the metric detail page for a "current value" chart api.
     * @param {string} api - The current value chart API (`Get<X>Chart[?arg]`); the history apis are derived by name
     * (first "Chart" -> "HistoryChart", then "HistoryShortChart").
     * @param {string} title - The page title.
     * @returns {string} "server_metrics.html?q1=...&q2=...&q3=...&title=...".
     */
    function MetricsUrl(api, title) {
        const h = api.replace("Chart", "HistoryChart");
        const s = h.replace("Chart", "ShortChart");
        return "server_metrics.html?q1=" + encodeURIComponent(api) + "&q2=" + encodeURIComponent(s) + "&q3=" + encodeURIComponent(h) + "&title=" + encodeURIComponent(title || "");
    }

    /**
     * Create a chart tile: an iframe of the chart page (not focusable, no pointer events) under a transparent button
     * that takes the clicks (mouse, touch, Enter / Space). The frame is out of the tab order; assistive technology reads it as
     * a titled frame ("Cpu use") whose chart image names its values (chart.js Describe: "Cpu use: Used 12 %, Free 88 %"), and
     * the button is named after the chart ("Show details of Cpu use"); both follow the chart page's title once it is known.
     * Its loader never takes the focus from this page (Sw.Focus.CanTake).
     * @param {object} o - Options.
     * @param {string} o.Api - Chart API name (see ChartUrl).
     * @param {string} [o.Extra] - Extra query string for the embedded chart.
     * @param {string} [o.Title] - Tool tip of the click target (also its accessible name until the chart title is known).
     * @param {?function():void} [o.OnClick] - Click action (none = a display only tile without a button).
     * @param {string} [o.Class] - Extra classes of the tile.
     * @returns {HTMLElement} The tile (div.sm-chart).
     */
    function ChartTile(o) {
        const f = Sw.CreateIFrame();
        f.tabIndex = -1;
        f.title = _TF("Chart", "Accessible name of a chart frame on the server pages until the chart title is known");
        f.src = Sw.Url.AppendTheme(ChartUrl(o.Api, "&transparent=true&m=false&noLabels=true&center=true" + (o.Extra || "")));
        let b = null;
        //  Name the frame and the button after the chart page title (set by the chart page when its data arrives)
        f.addEventListener("load", () => {
            let d = null;
            try {
                d = f.contentDocument;
            }
            catch {
            }
            if (!d || !d.head)
                return;
            const name = () => {
                const t = (d.title || "").trim();
                if (!t)
                    return;
                f.title = t;
                if (b)
                    b.setAttribute("aria-label", _T("Show details of {0}", t, "Accessible name of a chart tile on the server pages that opens its detail page, {0} is the chart title"));
            };
            name();
            new MutationObserver(name).observe(d.head, { subtree: true, childList: true, characterData: true });
        });
        if (o.OnClick) {
            b = Sw.el("button.sm-chart-click", { type: "button", title: o.Title, attrs: { "aria-label": Sw.ActionName(o.Title) } });
            b.addEventListener("click", ev => {
                if (Sw.BadClick(ev))
                    return;
                o.OnClick();
            });
            //  Hover frame (.sm-hot) only after a real mouse move over the tile: a pointer that rests where a menu / the theme
            //  changed (no movement) shows no leftover frame
            let at = null;
            b.addEventListener("pointerenter", ev => at = { X: ev.clientX, Y: ev.clientY });
            b.addEventListener("pointermove", ev => {
                if (ev.pointerType === "mouse" && (!at || Math.abs(ev.clientX - at.X) + Math.abs(ev.clientY - at.Y) > 2))
                    b.classList.add("sm-hot");
            });
            b.addEventListener("pointerleave", () => {
                at = null;
                b.classList.remove("sm-hot");
            });
        }
        return Sw.el("div.sm-chart" + (o.Class ? "." + o.Class : ""), null, f, b);
    }

    /**
     * Start an in-place reconciliation of the children of an element (polled lists only touch nodes that changed:
     * no flicker, the focus and selection are kept).
     * Call Add(e, init) for every wanted child in order, then Complete() to remove the left over children.
     * An existing child at the same position with the same outerHTML is kept (the new element is discarded);
     * `init(node)` is only called for nodes that are inserted, so event handlers should read per update data from
     * expandos set on the returned node (ex: `node.SmData = file`).
     * @param {HTMLElement} target - The element whose children are reconciled.
     * @returns {{Add: function(HTMLElement, function(HTMLElement):void=):HTMLElement, Complete: function():void}} The updater.
     */
    function ChildUpdater(target) {
        let count = target.children.length;
        let index = 0;
        return {
            Add(e, init) {
                if (index < count) {
                    const old = target.children[index];
                    ++index;
                    if (old.outerHTML === e.outerHTML)
                        return old;
                    target.replaceChild(e, old);
                }
                else {
                    ++index;
                    target.appendChild(e);
                }
                if (init)
                    init(e);
                return e;
            },
            Complete() {
                while (count > index) {
                    --count;
                    target.children[count].remove();
                }
            },
        };
    }

    /**
     * Show the outcome of an upload (one message): an error, the first failing file, the first already uploaded file,
     * or the first uploaded file (then `onUploaded` is called).
     * @param {{Error: (string|Error|null), Status: Array<number>}} res - Result of the upload library.
     * @param {File[]|FileList} files - The files (same order as res.Status).
     * @param {function():void} [onUploaded] - Called when at least one file was uploaded.
     */
    function ReportUpload(res, files, onUploaded) {
        if (!res)
            return;
        const err = res.Error;
        if (err) {
            Sw.Fail(err.message || String(err));
            return;
        }
        const ss = res.Status || [];
        const failed = ss.findIndex(s => s !== UploadOk && s !== UploadAlready);
        if (failed >= 0) {
            const code = ss[failed];
            const text = typeof window.fileUploaderStatusText === "function" ? window.fileUploaderStatusText(code) : String(code);
            Sw.Fail(_T("{0}, when uploading \"{1}\"", text, files[failed].name, "Text displayed when uploading of a file to a server failed.{0} is replaced with a message as to why the file failed.{1} is replaced with the name of the file"));
            return;
        }
        const already = ss.indexOf(UploadAlready);
        if (already >= 0) {
            Sw.Info(_T("File \"{0}\" was already uploaded", files[already].name, "Text displayed when a file have already been uploaded to a server.{0} is replaced with the name of the file"));
            return;
        }
        const ok = ss.indexOf(UploadOk);
        if (ok >= 0) {
            Sw.Info(_T("Uploaded \"{0}\"", files[ok].name, "Text displayed when a file was successfully uploaded to a server.{0} is replaced with the name of the file"));
            if (onUploaded)
                onUploaded();
        }
    }

    /**
     * Make an element an upload target for a server repo (click / Enter / Space opens the file picker, files can be
     * dropped on it, multiple files). Uses the public `fileUploaderSetup` of common/fileUploader.js, which toggles the
     * classes Dragging, Selecting and Uploading on the element.
     * @param {HTMLElement} el - The target (a button element, so it is keyboard and touch operable).
     * @param {string} repo - Repo name (ex: "Keys", "Current_<svc>", "Master_<svc>").
     * @param {function():void} [onUploaded] - Called after a successful upload.
     * @param {{Url:string, Auth:*}} [guard] - Disable the target for users without the role (Sw.Access.Guard; Url: a server method
     * with the same auth, ex: the page's table). Without it the target is disabled after the first refused request of the page.
     * @returns {boolean} False if the upload library is missing (the element is then disabled).
     */
    function UploadTarget(el, repo, onUploaded, guard) {
        if (typeof window.fileUploaderSetup !== "function") {
            el.disabled = true;
            el.title = _TF("File uploads are not available here (the upload service is missing)", "Tool tip of an upload button when the file upload service is missing");
            return false;
        }
        window.fileUploaderSetup(el, repo, null, (e, res, files) => ReportUpload(res, files, onUploaded), null, true);
        if (Sw.Access)
            Sw.Access.Guard(el, guard || {});
        return true;
    }

    /**
     * Fill an element with a time stamp: short text, full tool tip (prefixed), click copies the raw value.
     * @param {HTMLElement} e - The element.
     * @param {string} iso - The time stamp (ISO text from the server).
     * @param {string} prefix - Tool tip line shown above the full time.
     * @returns {HTMLElement} The element.
     */
    function TimeCell(e, iso, prefix) {
        const ts = Sw.Format.TimeStamp(new Date(iso));
        e.textContent = ts[1];
        e.title = prefix ? (prefix + "\n" + ts[0]) : ts[0];
        Sw.Clipboard.CopyOnClick(e, iso, { AddTitle: true });
        return e;
    }

    /**
     * Join translated lines into a multi line text (translated literals may not contain line breaks).
     * @param {...string} lines - Lines ("" = an empty line).
     * @returns {string} The text.
     */
    function Lines(...lines) {
        return lines.join("\n");
    }

    /**
     * Use the server's time zone for the time labels of the charts created after this call (the history charts get UTC labels from
     * the server; chart.html moves them with its timeoffset parameter). Without a call (or with an unusable info) the charts show
     * the viewer's local time.
     * @param {?{Time: string, Utc: string}} info - GetServerInfo reply: Time = server local time (no zone), Utc = ISO UTC time.
     * @returns {number|string} The offset used: minutes, or "local".
     */
    function UseServerTimeZone(info) {
        let m = NaN;
        if (info && info.Time && info.Utc)
            m = (Date.parse(String(info.Time).replace(" ", "T") + "Z") - Date.parse(info.Utc)) / 60000;
        //  Time zones are whole quarters of an hour (the two stamps are taken a few ms apart)
        TimeOffset = Number.isFinite(m) ? Math.round(m / 15) * 15 : "local";
        //  the shared time rule (core/README "Times"): the sidebar line and the log viewer learn the server's zone
        if (typeof TimeOffset === "number" && Sw.Format && typeof Sw.Format.SetServerZone === "function")
            Sw.Format.SetServerZone(TimeOffset);
        return TimeOffset;
    }

    /**
     * Show the meter level of a KPI tile (Sw.Kpi) also as text (status never by colour alone, Design v2, PORTING.md B18): a "High" /
     * "Critical" badge before the context line.
     * @param {object} kpi - The tile (Sw.Kpi).
     * @param {string} text - The context line ("28.36 GB of 63.35 GB").
     */
    function KpiSub(kpi, text) {
        const lv = kpi.Level();
        if (lv === "ok") {
            kpi.Set({ Sub: text });
            return;
        }
        kpi.Set({
            Sub: [lv === "danger"
                ? Sw.Badge(_TF("Critical", "Badge on a server KPI tile when the use is above the danger threshold"), "error")
                : Sw.Badge(_TF("High", "Badge on a server KPI tile when the use is above the warning threshold"), "warning"), Sw.el("span", { text })],
        });
    }

    /**
     * An upload button (Sw.Button, secondary, upload icon and a word) that is also a drop target for a server repo (UploadTarget;
     * files dragged over it: class Dragging, styled in smShared.css .sm-dropbtn).
     * @param {object} o - Options.
     * @param {string} o.Text - The visible text ("Upload key files").
     * @param {string} o.Title - Tool tip.
     * @param {string} o.Repo - Repo name.
     * @param {function():void} [o.OnUploaded] - After a successful upload.
     * @param {{Url:string, Auth:*}} [o.Guard] - See UploadTarget.
     * @param {boolean} [o.Small] - A small button (card heads).
     * @returns {object} The button (Sw.Button).
     */
    function UploadButton(o) {
        const b = new Sw.Button({ Text: o.Text, Icon: "upload", Title: o.Title, Small: !!o.Small, Class: "sm-dropbtn" });
        UploadTarget(b.E, o.Repo, o.OnUploaded, o.Guard);
        return b;
    }

    /**
     * Put a live data table (explore/table.js Sw.Table, page mode: the frame takes the free height, the page size follows the height)
     * into a Design v2 fill page (Sw.PageLayout Type "fill"): the table's own compact header is dropped (the page has one), its
     * refresh line ("Live, updates every 5 s") moves under the page description.
     * @param {object} page - The page (Sw.PageLayout).
     * @param {string} url - The table api url.
     * @returns {Promise<object>} The table (UpdateNow()).
     */
    async function FillTable(page, url) {
        const host = Sw.el("div.sw-fill.sm-fill");
        page.Add(host);
        const t = await Sw.Table.Create({ Url: url, Element: host, Page: true });
        if (t.PH) {
            t.PH.remove();
            if (t.PHDesc && page.Header)
                page.Header.E.querySelector(".sw-ph-text").append(t.PHDesc);
        }
        return t;
    }

    /**
     * The title of a destructive confirmation that names the action and its target (the shared rule of Sw.Dialog.DangerTitle,
     * ex: "Kill Mail?", "Delete appsettings.json?"); on an older framework without it the given fallback title.
     * @param {string} verb - The action (translated, ex: "Kill").
     * @param {string} target - The item it changes (a name).
     * @param {function():string} fallback - The old title.
     * @returns {string} The title.
     */
    function DangerTitle(verb, target, fallback) {
        return Sw.Dialog && typeof Sw.Dialog.DangerTitle === "function" && target ? Sw.Dialog.DangerTitle(verb, target) : fallback();
    }

    /**
     * The last part of a file or folder path ("C:\\Services\\Mail\\1.2.0" -> "1.2.0").
     * @param {string} path - The path.
     * @returns {string} The name.
     */
    function BaseName(path) {
        const s = String(path || "").replace(/[\\/]+$/, "");
        return s.substring(Math.max(s.lastIndexOf("/"), s.lastIndexOf("\\")) + 1) || s;
    }

    /**
     * The ServerManager page helpers. ReportUpload, UploadTarget, UploadButton and FillTable are shared components now
     * (Sw.ReportUpload, Sw.UploadTarget, Sw.UploadButton, Sw.FillTable in ui/page.js); the SmShared names stay as aliases (the local
     * versions only run on an older framework without them). The aliases keep the old classes sm-dropbtn / sm-fill.
     */
    window.SmShared = Object.freeze({
        UseServerTimeZone,
        ChartUrl,
        MetricsUrl,
        ChartTile,
        ChildUpdater,
        ReportUpload: Sw.ReportUpload || ReportUpload,
        UploadTarget: Sw.UploadTarget || UploadTarget,
        TimeCell,
        Lines,
        KpiSub,
        UploadButton: Sw.UploadButton ? o => Sw.UploadButton(Object.assign({}, o, { Class: ((o && o.Class) || "") + " sm-dropbtn" })) : UploadButton,
        FillTable: Sw.FillTable ? (page, url) => Sw.FillTable(page, url, { Class: "sm-fill" }) : FillTable,
        DangerTitle,
        BaseName,
    });
})();
